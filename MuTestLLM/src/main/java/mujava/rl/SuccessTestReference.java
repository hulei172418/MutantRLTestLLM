package mujava.rl;

/**
 * One previously successful same-method generated test that can be used as a
 * regeneration reference template.
 */
public final class SuccessTestReference {
    public String mutantId;
    public String testName;
    public String testJavaFile;
    public String action;
    public double reward;
    public String code;
    public String operator;
    public String sourceClassName;
    public String sourceMethod;
    public String line;
    public String relation;
    public String observablePlanKind;
    public String testEntryKind;
    public String entryInvocationKind;
    public double similarityScore;
}
